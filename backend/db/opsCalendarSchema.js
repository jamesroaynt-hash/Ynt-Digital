// Operations calendar: delivery schedules and other logistics dates. Kept in
// its own file like the HR records schema; idempotent on SQLite and Postgres.

function opsCalendarStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  return [
    // item_id / qty / supplier are optional: a supplier delivery names what is
    // coming and how much; a courier pickup or a count needs neither.
    `CREATE TABLE IF NOT EXISTS ops_calendar_events (
      id ${id},
      event_date TEXT NOT NULL,
      event_time TEXT,
      category TEXT NOT NULL DEFAULT 'Supplier Delivery',
      title TEXT NOT NULL,
      item_id TEXT,
      qty INTEGER,
      supplier TEXT,
      status TEXT NOT NULL DEFAULT 'Scheduled',
      repeat_rule TEXT NOT NULL DEFAULT 'none',
      notes TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_ops_calendar_events_date ON ops_calendar_events(event_date)',
  ];
}

async function ensureOpsCalendarSchema(db) {
  for (const sql of opsCalendarStatements(db)) {
    await db.exec(sql);
  }
}

module.exports = { ensureOpsCalendarSchema, opsCalendarStatements };
