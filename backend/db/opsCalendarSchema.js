// Operations calendar: incoming orders from suppliers, placed on the calendar
// by their expected arrival date (event_date). Kept in its own file like the
// HR records schema; idempotent on SQLite and Postgres.

function opsCalendarStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  return [
    `CREATE TABLE IF NOT EXISTS ops_calendar_events (
      id ${id},
      event_date TEXT NOT NULL,
      event_time TEXT,
      category TEXT NOT NULL DEFAULT 'Supplier Order',
      title TEXT NOT NULL,
      item_id TEXT,
      qty INTEGER,
      supplier TEXT,
      status TEXT NOT NULL DEFAULT 'Ordered',
      repeat_rule TEXT NOT NULL DEFAULT 'none',
      notes TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_ops_calendar_events_date ON ops_calendar_events(event_date)',
  ];
}

// Supplier-order fields added after the first release of the table.
const ORDER_COLUMNS = [
  ['po_number', 'TEXT'],
  ['order_date', 'TEXT'],
  ['qty_received', 'INTEGER'],
  ['amount', 'REAL'],
  ['courier', 'TEXT'],
  ['tracking_no', 'TEXT'],
];

// Scoped to the app's own schema: Supabase's auth schema has tables of its own
// and matching on the table name alone has crashed startup before.
async function ensureColumn(db, table, column, definition) {
  if (db.type === 'postgres') {
    const found = await db.prepare(`
      SELECT column_name FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?
    `).get(table, column);
    if (found) return;
  } else {
    const columns = await db.prepare(`PRAGMA table_info(${table})`).all();
    if (columns.some((c) => c.name === column)) return;
  }
  await db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
}

async function ensureOpsCalendarSchema(db) {
  for (const sql of opsCalendarStatements(db)) {
    await db.exec(sql);
  }
  for (const [column, definition] of ORDER_COLUMNS) {
    await ensureColumn(db, 'ops_calendar_events', column, db.type === 'postgres' && definition === 'REAL' ? 'DOUBLE PRECISION' : definition);
  }
}

module.exports = { ensureOpsCalendarSchema, opsCalendarStatements };
