// Tool links: the top-bar dropdown of outside sites (name + URL, optional
// icon) the super admin curates for everyone. Idempotent on SQLite and Postgres.

function toolLinksStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  return [
    `CREATE TABLE IF NOT EXISTS tool_links (
      id ${id},
      name TEXT NOT NULL,
      url TEXT NOT NULL,
      icon TEXT,
      sort_order INTEGER NOT NULL DEFAULT 0,
      created_by INTEGER,
      created_at ${ts}
    )`,
  ];
}

async function ensureToolLinksSchema(db) {
  for (const sql of toolLinksStatements(db)) {
    await db.exec(sql);
  }
}

module.exports = { ensureToolLinksSchema, toolLinksStatements };
