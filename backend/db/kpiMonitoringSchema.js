// KPI Monitoring: HR's manual KPI records for CSR and RMO. Replaces the old
// department KPI (kpi_items / kpi_results), whose tables stay for history.
//   kpi_records — one row per employee, KPI and period: CSR "orders" and
//     "roas", RMO "rts". period_type 'daily' (period_key YYYY-MM-DD) or
//     'monthly' (YYYY-MM); daily and monthly are separate rows. HR types both
//     the target and the actual; nothing is fetched from another system.
//     The UNIQUE key is what stops duplicates.
//   kpi_record_history — every create and every correction, with the values
//     before and after, who did it and when. Rows are only ever added.
//   kpi_defaults — HR's default target per KPI and period type, filled in
//     when a record is saved without a target (RTS starts at 12%).
// Idempotent on SQLite and Postgres, like the other module schemas.

function kpiMonitoringStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  return [
    `CREATE TABLE IF NOT EXISTS kpi_records (
      id ${id},
      user_id INTEGER NOT NULL,
      department TEXT NOT NULL,
      kpi_type TEXT NOT NULL,
      period_type TEXT NOT NULL,
      period_key TEXT NOT NULL,
      target ${real},
      actual ${real},
      remarks TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (user_id, kpi_type, period_type, period_key)
    )`,
    'CREATE INDEX IF NOT EXISTS idx_kpi_records_period ON kpi_records(period_type, period_key)',
    `CREATE TABLE IF NOT EXISTS kpi_record_history (
      id ${id},
      record_id INTEGER NOT NULL,
      action TEXT NOT NULL,
      old_target ${real},
      old_actual ${real},
      old_remarks TEXT,
      new_target ${real},
      new_actual ${real},
      new_remarks TEXT,
      changed_by INTEGER,
      changed_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_kpi_record_history_record ON kpi_record_history(record_id)',
    // The CSR team's ad spend, one amount per day for all CSRs. Every CSR's
    // ROAS divides by it; a month's ad spend is the sum of its days.
    `CREATE TABLE IF NOT EXISTS kpi_ad_spend (
      id ${id},
      work_date TEXT NOT NULL UNIQUE,
      amount ${real},
      updated_by INTEGER,
      updated_at ${ts}
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_ad_spend_history (
      id ${id},
      work_date TEXT NOT NULL,
      old_amount ${real},
      new_amount ${real},
      changed_by INTEGER,
      changed_at ${ts}
    )`,
    // The CSR team's orders target for a day or a month; each CSR's own target
    // is it divided by the active CSRs, unless HR set theirs by hand.
    `CREATE TABLE IF NOT EXISTS kpi_team_targets (
      id ${id},
      kpi_type TEXT NOT NULL,
      period_type TEXT NOT NULL,
      period_key TEXT NOT NULL,
      target ${real},
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (kpi_type, period_type, period_key)
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_team_target_history (
      id ${id},
      kpi_type TEXT NOT NULL,
      period_type TEXT NOT NULL,
      period_key TEXT NOT NULL,
      old_target ${real},
      new_target ${real},
      changed_by INTEGER,
      changed_at ${ts}
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_defaults (
      id ${id},
      kpi_type TEXT NOT NULL,
      period_type TEXT NOT NULL,
      target ${real},
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (kpi_type, period_type)
    )`,
  ];
}

async function ensureKpiMonitoringSchema(db) {
  for (const sql of kpiMonitoringStatements(db)) {
    await db.exec(sql);
  }
  // ROAS is worked out from what HR types: gross sales ÷ ad spend. Both are
  // kept on the record (and before/after in the history) so the ROAS can be
  // traced back to its two numbers.
  const real = db.type === 'postgres' ? 'DOUBLE PRECISION' : 'REAL';
  const added = [
    ['kpi_records', 'ad_spend'], ['kpi_records', 'gross_sales'],
    ['kpi_record_history', 'old_ad_spend'], ['kpi_record_history', 'old_gross_sales'],
    ['kpi_record_history', 'new_ad_spend'], ['kpi_record_history', 'new_gross_sales'],
  ];
  for (const [table, name] of added) {
    if (db.type === 'postgres') {
      await db.exec(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${name} ${real}`);
    } else {
      const columns = await db.prepare(`PRAGMA table_info(${table})`).all();
      if (!columns.some((c) => c.name === name)) await db.exec(`ALTER TABLE ${table} ADD COLUMN ${name} ${real}`);
    }
  }
}

module.exports = { ensureKpiMonitoringSchema };
