// Performance: the two scoring categories that sit beside the peer Evaluation
// (which they never touch).
//   employee_tracker_marks — the Employee Tracker's daily marks (Standup, EOD,
//     Self-Care, WAM, Discord Live) with the day's note and EOD link. These used
//     to live in one browser's localStorage; Compliance is scored from them.
//   kpi_items — KPI rows: a department's template (department set) or one
//     person's own extra KPI (user_id set).
//   kpi_user_overrides — per-person tweak of a department KPI: hide it or give
//     that person a different target.
//   kpi_results — the actual number HR enters per person, KPI and period.
// Kept in its own file like the other module schemas; idempotent on SQLite and
// Postgres.

function performanceStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  return [
    `CREATE TABLE IF NOT EXISTS employee_tracker_marks (
      id ${id},
      metric TEXT NOT NULL,
      user_id INTEGER NOT NULL,
      work_date TEXT NOT NULL,
      state TEXT,
      note TEXT,
      link TEXT,
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (metric, user_id, work_date)
    )`,
    'CREATE INDEX IF NOT EXISTS idx_tracker_marks_date ON employee_tracker_marks(work_date)',
    `CREATE TABLE IF NOT EXISTS kpi_items (
      id ${id},
      department TEXT,
      user_id INTEGER,
      label TEXT NOT NULL,
      unit TEXT,
      target ${real} NOT NULL DEFAULT 0,
      direction TEXT NOT NULL DEFAULT 'higher',
      weight ${real} NOT NULL DEFAULT 1,
      position INTEGER NOT NULL DEFAULT 0,
      is_active INTEGER NOT NULL DEFAULT 1,
      created_at ${ts}
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_user_overrides (
      id ${id},
      user_id INTEGER NOT NULL,
      item_id INTEGER NOT NULL,
      hidden INTEGER NOT NULL DEFAULT 0,
      target ${real},
      UNIQUE (user_id, item_id)
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_results (
      id ${id},
      period TEXT NOT NULL,
      user_id INTEGER NOT NULL,
      item_id INTEGER NOT NULL,
      actual ${real},
      note TEXT,
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (period, user_id, item_id)
    )`,
    'CREATE INDEX IF NOT EXISTS idx_kpi_results_period ON kpi_results(period, user_id)',
  ];
}

async function ensurePerformanceSchema(db) {
  for (const sql of performanceStatements(db)) {
    await db.exec(sql);
  }
}

module.exports = { ensurePerformanceSchema, performanceStatements };
