// Performance: the two scoring categories that sit beside the peer Evaluation
// (which they never touch).
//   employee_tracker_marks — the Employee Tracker's daily marks (Standup, EOD,
//     Self-Care, WAM, Discord Live) with the day's note and EOD link, plus the
//     Confirmed Orders tab's number per CSR per day (metric 'orders', value).
//     These used to live in one browser's localStorage; Compliance is scored
//     from them.
//   kpi_items — KPI rows: a department's template (department set) or one
//     person's own extra KPI (user_id set).
//   kpi_user_overrides — per-person tweak of a department KPI: hide it or give
//     that person a different target.
//   kpi_results — the actual number HR enters per person, KPI and month.
//   kpi_period_targets — a KPI's target for one month (CSR's monthly orders
//     target changes month to month); without one the KPI's own target applies.
//   kpi_daily — for a "daily" KPI (e.g. CSR total orders): HR's number per
//     person per day; the month's actual is their sum, and the monthly target
//     is split over the person's scheduled days to give a daily target.
// Kept in its own file like the other module schemas; idempotent on SQLite and
// Postgres.

function performanceStatements(db) {
  const pg = db.type === 'postgres';
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const ts = pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))";
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  return [
    `CREATE TABLE IF NOT EXISTS employee_tracker_marks (
      id ${id},
      metric TEXT NOT NULL,
      user_id INTEGER NOT NULL,
      work_date TEXT NOT NULL,
      state TEXT,
      note TEXT,
      link TEXT,
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (metric, user_id, work_date)
    )`,
    'CREATE INDEX IF NOT EXISTS idx_tracker_marks_date ON employee_tracker_marks(work_date)',
    `CREATE TABLE IF NOT EXISTS kpi_items (
      id ${id},
      department TEXT,
      user_id INTEGER,
      label TEXT NOT NULL,
      unit TEXT,
      target ${real} NOT NULL DEFAULT 0,
      direction TEXT NOT NULL DEFAULT 'higher',
      weight ${real} NOT NULL DEFAULT 1,
      position INTEGER NOT NULL DEFAULT 0,
      is_active INTEGER NOT NULL DEFAULT 1,
      created_at ${ts}
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_user_overrides (
      id ${id},
      user_id INTEGER NOT NULL,
      item_id INTEGER NOT NULL,
      hidden INTEGER NOT NULL DEFAULT 0,
      target ${real},
      UNIQUE (user_id, item_id)
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_results (
      id ${id},
      period TEXT NOT NULL,
      user_id INTEGER NOT NULL,
      item_id INTEGER NOT NULL,
      actual ${real},
      note TEXT,
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (period, user_id, item_id)
    )`,
    'CREATE INDEX IF NOT EXISTS idx_kpi_results_period ON kpi_results(period, user_id)',
    `CREATE TABLE IF NOT EXISTS kpi_period_targets (
      id ${id},
      item_id INTEGER NOT NULL,
      period TEXT NOT NULL,
      target ${real} NOT NULL,
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (item_id, period)
    )`,
    `CREATE TABLE IF NOT EXISTS kpi_daily (
      id ${id},
      work_date TEXT NOT NULL,
      user_id INTEGER NOT NULL,
      item_id INTEGER NOT NULL,
      value ${real},
      updated_by INTEGER,
      updated_at ${ts},
      UNIQUE (work_date, user_id, item_id)
    )`,
  ];
}

function pgOr(db, pg, sqlite) {
  return db.type === 'postgres' ? pg : sqlite;
}

async function ensurePerformanceSchema(db) {
  for (const sql of performanceStatements(db)) {
    await db.exec(sql);
  }
  // entry: 'monthly' (one number a month) or 'daily' (summed from kpi_daily).
  // split: 1 = the target is the whole department's, shared out per person.
  //   (entry 'orders' is a daily KPI read from the tracker's Confirmed Orders.)
  // employee_tracker_marks.value: the Confirmed Orders number.
  const added = [
    ['kpi_items', 'entry', "TEXT NOT NULL DEFAULT 'monthly'"],
    ['kpi_items', 'split', 'INTEGER NOT NULL DEFAULT 0'],
    ['employee_tracker_marks', 'value', pgOr(db, 'DOUBLE PRECISION', 'REAL')],
  ];
  for (const [table, name, definition] of added) {
    if (db.type === 'postgres') {
      await db.exec(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${name} ${definition}`);
    } else {
      const columns = await db.prepare(`PRAGMA table_info(${table})`).all();
      if (!columns.some((c) => c.name === name)) await db.exec(`ALTER TABLE ${table} ADD COLUMN ${name} ${definition}`);
    }
  }
}

module.exports = { ensurePerformanceSchema, performanceStatements };
