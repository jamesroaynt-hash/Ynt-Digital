// HR records module schema: 201 files (documents + memos), the HR calendar,
// trainee onboarding, playbooks and KPI allowances. Kept in its own file like
// the Meta Ads schema; every statement is idempotent and runs on both SQLite
// and Postgres.
//
// Conventions shared with the rest of the schema:
// - dates are 'YYYY-MM-DD' TEXT
// - files are linked, not uploaded: the document lives in Google Drive and the
//   row keeps its URL (same as expense receipts)

function dialect(db) {
  const pg = db.type === 'postgres';
  return {
    id: pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT',
    ts: pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))",
    num: pg ? 'DOUBLE PRECISION' : 'REAL',
  };
}

function hrRecordsStatements(db) {
  const { id, ts, num } = dialect(db);
  return [
    // One table for both halves of an employee's 201 file: kind 'document'
    // (contract, NDA, data sheet...) and kind 'memo' (NTE, NOD, warnings).
    `CREATE TABLE IF NOT EXISTS hr_documents (
      id ${id},
      user_id INTEGER NOT NULL,
      kind TEXT NOT NULL DEFAULT 'document',
      doc_type TEXT NOT NULL,
      title TEXT,
      status TEXT,
      issue_date TEXT,
      expiry_date TEXT,
      file_url TEXT,
      remarks TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_hr_documents_user ON hr_documents(user_id, kind)',

    // Hand-entered events only. Payroll cutoffs, birthdays, approved leaves and
    // document expiries are derived on the page, never stored here.
    `CREATE TABLE IF NOT EXISTS hr_calendar_events (
      id ${id},
      event_date TEXT NOT NULL,
      category TEXT NOT NULL DEFAULT 'HR Task',
      title TEXT NOT NULL,
      amount ${num},
      user_id INTEGER,
      notes TEXT,
      repeat_rule TEXT NOT NULL DEFAULT 'none',
      status TEXT NOT NULL DEFAULT 'Upcoming',
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_hr_calendar_events_date ON hr_calendar_events(event_date)',

    // A trainee can start before they have an account, so user_id is optional.
    // progress holds the checklist, daily targets and readiness marks as JSON.
    `CREATE TABLE IF NOT EXISTS hr_trainees (
      id ${id},
      full_name TEXT NOT NULL,
      user_id INTEGER,
      department TEXT NOT NULL DEFAULT 'CSR',
      start_date TEXT,
      trainer TEXT,
      stage TEXT,
      employee_code TEXT,
      status TEXT NOT NULL DEFAULT 'In Training',
      progress TEXT,
      remarks TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,

    // scope 'employee' = an RRM / playbook assigned to one person;
    // scope 'hr' = HR's own SOPs and references.
    `CREATE TABLE IF NOT EXISTS hr_playbooks (
      id ${id},
      scope TEXT NOT NULL DEFAULT 'employee',
      user_id INTEGER,
      department TEXT,
      title TEXT NOT NULL,
      category TEXT,
      link TEXT,
      description TEXT,
      progress INTEGER NOT NULL DEFAULT 0,
      verified INTEGER NOT NULL DEFAULT 0,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_hr_playbooks_scope ON hr_playbooks(scope, user_id)',

    `CREATE TABLE IF NOT EXISTS hr_kpi_allowances (
      id ${id},
      user_id INTEGER NOT NULL,
      period_label TEXT NOT NULL,
      kpi_score ${num},
      amount ${num},
      status TEXT NOT NULL DEFAULT 'Awaiting Evaluation',
      payroll_status TEXT,
      remarks TEXT,
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_hr_kpi_allowances_user ON hr_kpi_allowances(user_id)',

    // Small HR-wide settings (the KPI allowance tiers), stored as JSON text.
    `CREATE TABLE IF NOT EXISTS hr_settings (
      key TEXT PRIMARY KEY,
      value TEXT,
      updated_at ${ts}
    )`,
  ];
}

async function ensureHrRecordsSchema(db) {
  for (const sql of hrRecordsStatements(db)) {
    await db.exec(sql);
  }
}

module.exports = { ensureHrRecordsSchema, hrRecordsStatements };
