// Training Center schema: trainings (lessons, materials and quiz kept as JSON
// on the row), each employee's progress, and the certificates earned. Kept in
// its own file like the Meta Ads and HR records schemas; idempotent, and runs
// on both SQLite and Postgres.
//
// Learners are the dashboard's own accounts (users.id) — there is no second
// user list. Who a training is for is stored as JSON on the training:
// { all: true } or { departments: [...], user_ids: [...] }.

function dialect(db) {
  const pg = db.type === 'postgres';
  return {
    id: pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT',
    ts: pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))",
    num: pg ? 'DOUBLE PRECISION' : 'REAL',
  };
}

const DEFAULT_CATEGORIES = [
  'Company Orientation',
  'CSR Management',
  'POS / Pancake',
  'Sales & Marketing',
  'Facebook / Meta Ads',
  'Logistics',
  'RMO',
  'HR & Compliance',
  'Leadership',
];

function trainingStatements(db) {
  const { id, ts, num } = dialect(db);
  return [
    `CREATE TABLE IF NOT EXISTS training_categories (
      id ${id},
      name TEXT NOT NULL UNIQUE,
      sort_order INTEGER NOT NULL DEFAULT 0
    )`,

    // lessons:   [{ id, title, url, minutes }]
    // materials: [{ name, url }]
    // quiz:      [{ id, type, question, options, answer, points }] — the answer
    //            key never leaves the server for a learner.
    `CREATE TABLE IF NOT EXISTS trainings (
      id ${id},
      title TEXT NOT NULL,
      description TEXT,
      category TEXT,
      instructions TEXT,
      lessons TEXT,
      materials TEXT,
      quiz TEXT,
      passing_score INTEGER NOT NULL DEFAULT 80,
      estimated_minutes INTEGER NOT NULL DEFAULT 0,
      audience TEXT,
      required INTEGER NOT NULL DEFAULT 0,
      due_date TEXT,
      status TEXT NOT NULL DEFAULT 'draft',
      created_by INTEGER,
      created_at ${ts},
      updated_at ${ts}
    )`,

    `CREATE TABLE IF NOT EXISTS training_progress (
      id ${id},
      user_id INTEGER NOT NULL,
      training_id INTEGER NOT NULL,
      status TEXT NOT NULL DEFAULT 'in_progress',
      lessons_done TEXT,
      notes TEXT,
      attempts INTEGER NOT NULL DEFAULT 0,
      last_score ${num},
      best_score ${num},
      last_result TEXT,
      started_at ${ts},
      completed_at TEXT,
      updated_at ${ts}
    )`,
    'CREATE UNIQUE INDEX IF NOT EXISTS idx_training_progress_user ON training_progress(user_id, training_id)',
    'CREATE INDEX IF NOT EXISTS idx_training_progress_training ON training_progress(training_id)',

    `CREATE TABLE IF NOT EXISTS training_certificates (
      id ${id},
      user_id INTEGER NOT NULL,
      training_id INTEGER NOT NULL,
      code TEXT NOT NULL UNIQUE,
      score ${num},
      training_title TEXT,
      issued_at ${ts}
    )`,
    'CREATE UNIQUE INDEX IF NOT EXISTS idx_training_certificates_user ON training_certificates(user_id, training_id)',
  ];
}

async function ensureTrainingSchema(db) {
  for (const sql of trainingStatements(db)) {
    await db.exec(sql);
  }
  const row = await db.prepare('SELECT COUNT(*) AS n FROM training_categories').get();
  if (!Number(row?.n)) {
    for (let i = 0; i < DEFAULT_CATEGORIES.length; i += 1) {
      await db.prepare('INSERT INTO training_categories (name, sort_order) VALUES (?, ?)').run(DEFAULT_CATEGORIES[i], i + 1);
    }
  }
}

module.exports = { ensureTrainingSchema, trainingStatements, DEFAULT_CATEGORIES };
