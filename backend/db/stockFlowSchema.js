// Stock flow schema: the daily stock-in / stock-out / returns / count cycle
// that sits on top of the inventory table. Kept in its own file like the HR
// records schema; every statement is idempotent and runs on SQLite and Postgres.
//
// Every stock change still lands in inventory_logs. The two columns added here
// say which step of the cycle wrote it (movement) and what it belongs to (ref),
// so the balance report can split a day into in / out / returns / adjustments.

function dialect(db) {
  const pg = db.type === 'postgres';
  return {
    id: pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT',
    ts: pg ? 'TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP' : "TEXT NOT NULL DEFAULT (datetime('now'))",
    tsNull: pg ? 'TIMESTAMPTZ' : 'TEXT',
  };
}

function stockFlowStatements(db) {
  const { id, ts, tsNull } = dialect(db);
  return [
    // One stock-out per Manila day. The day's row is the lock that stops the
    // same picking list from being deducted twice; voiding it puts the stock
    // back and frees the day to be posted again.
    `CREATE TABLE IF NOT EXISTS stock_out_batches (
      id ${id},
      out_date TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'posted',
      orders INTEGER NOT NULL DEFAULT 0,
      planned_pcs INTEGER NOT NULL DEFAULT 0,
      packed_pcs INTEGER NOT NULL DEFAULT 0,
      unmapped_json TEXT,
      notes TEXT,
      posted_by INTEGER,
      posted_at ${ts},
      voided_by INTEGER,
      voided_at ${tsNull},
      void_reason TEXT
    )`,
    // planned_qty is what the picking list asked for, packed_qty what actually
    // left; a difference needs a reason.
    `CREATE TABLE IF NOT EXISTS stock_out_lines (
      id ${id},
      batch_id INTEGER NOT NULL,
      item_id TEXT NOT NULL,
      planned_qty INTEGER NOT NULL DEFAULT 0,
      packed_qty INTEGER NOT NULL DEFAULT 0,
      reason TEXT,
      pages_json TEXT
    )`,
    'CREATE INDEX IF NOT EXISTS idx_stock_out_lines_batch ON stock_out_lines(batch_id)',

    // One inspection per returned parcel, keyed by its lower-cased tracking
    // number so a parcel scanned twice can still only be restocked once.
    `CREATE TABLE IF NOT EXISTS return_inspections (
      id ${id},
      tracking_key TEXT NOT NULL UNIQUE,
      scan_id INTEGER,
      item_id TEXT,
      expected_pcs INTEGER NOT NULL DEFAULT 0,
      sellable_qty INTEGER NOT NULL DEFAULT 0,
      damaged_qty INTEGER NOT NULL DEFAULT 0,
      status TEXT NOT NULL,
      notes TEXT,
      inspected_by INTEGER,
      inspected_at ${ts}
    )`,

    // Physical counts. expected_qty is the system's number at the time of the
    // count; the variance is what the count adjusted the stock by.
    `CREATE TABLE IF NOT EXISTS stock_counts (
      id ${id},
      count_date TEXT NOT NULL,
      item_id TEXT NOT NULL,
      expected_qty INTEGER NOT NULL DEFAULT 0,
      counted_qty INTEGER NOT NULL DEFAULT 0,
      variance INTEGER NOT NULL DEFAULT 0,
      reason TEXT,
      counted_by INTEGER,
      created_at ${ts}
    )`,
    'CREATE INDEX IF NOT EXISTS idx_stock_counts_item ON stock_counts(item_id, count_date)',

    `CREATE TABLE IF NOT EXISTS stock_flow_settings (
      key TEXT PRIMARY KEY,
      value TEXT,
      updated_at ${ts}
    )`,
  ];
}

// Scoped to the app's own schema: Supabase's auth schema has tables of its own
// and matching on the table name alone has crashed startup before.
async function ensureColumn(db, table, column, definition) {
  if (db.type === 'postgres') {
    const found = await db.prepare(`
      SELECT column_name FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?
    `).get(table, column);
    if (found) return;
  } else {
    const columns = await db.prepare(`PRAGMA table_info(${table})`).all();
    if (columns.some((c) => c.name === column)) return;
  }
  await db.exec(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
}

async function ensureStockFlowSchema(db) {
  for (const sql of stockFlowStatements(db)) {
    await db.exec(sql);
  }
  await ensureColumn(db, 'inventory_logs', 'movement', 'TEXT');
  await ensureColumn(db, 'inventory_logs', 'ref', 'TEXT');
  await db.exec('CREATE INDEX IF NOT EXISTS idx_inventory_logs_created ON inventory_logs(created_at)');
}

module.exports = { ensureStockFlowSchema, stockFlowStatements };
